#!/usr/bin/env node
// Writes the Universal Enchanter's "Add a slot" table (npc/enchanter.txt,
// between the "slot table" markers) from rAthena's official slotting NPCs,
// Seiyablem and Leablem (npc/merchants/socket_enchant.txt and
// socket_enchant2.txt), at the rAthena commit the app pins in
// config/VENDOR_PINS. Every ID is checked in that commit's Renewal item_db:
// both items must exist, be equipment on the same places, and the second
// must have more slots.
//
//   node tools/slot-table.cjs
//
// The app clone: $SNPC_APP, else ragnarokoffline.app next to the main
// checkout. The rAthena clone: $SNPC_RATHENA, else rathena next to it; it
// must have the pinned commit (git fetch flux).
'use strict';
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.join(__dirname, '..');
const git = (dir, ...a) => execFileSync('git', ['-C', dir, ...a], { encoding: 'utf8', maxBuffer: 1 << 28 });
const die = msg => { console.error(`error: ${msg}`); process.exit(1); };

const mainRoot = path.resolve(git(ROOT, 'rev-parse', '--path-format=absolute', '--git-common-dir').trim(), '..');
const APP = process.env.SNPC_APP || path.join(path.dirname(mainRoot), 'ragnarokoffline.app');
const RATHENA = process.env.SNPC_RATHENA || path.join(path.dirname(mainRoot), 'rathena');

const pins = fs.readFileSync(path.join(APP, 'config', 'VENDOR_PINS'), 'utf8');
const pinLine = pins.split('\n').find(l => /^rathena\s/.test(l));
if (!pinLine) die('no rathena line in VENDOR_PINS');
const PIN = pinLine.trim().split(/\s+/)[2];
const show = file => git(RATHENA, 'show', `${PIN}:${file}`);

// Official entries: callfunc "Func_Socket(2)",<item>,<slotted item>,<low>,<high>,...
// succeeds when <low> < rand(1,100) < <high>. Lines commented out are not
// offered by the NPCs and are skipped. Leablem's Hat of the Sun God is
// written out in place: rand(1,100) between two numbers, then delitem/getitem.
const entries = [];
for (const file of ['npc/merchants/socket_enchant.txt', 'npc/merchants/socket_enchant2.txt']) {
    const text = show(file);
    for (const line of text.split('\n')) {
        const code = line.replace(/\/\/.*$/, '');
        const m = code.match(/callfunc\s+"Func_Socket2?"\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)/);
        if (m) entries.push({ from: +m[1], to: +m[2], chance: +m[4] - +m[3] - 1, file });
    }
    const re = /set \.@a, rand\(1,100\);\s*if \(\(\.@a > (\d+)\) && \(\.@a < (\d+)\)\)[\s\S]*?delitem (\d+),1;[\s\S]*?getitem (\d+),1;/g;
    for (const m of text.matchAll(re))
        entries.push({ from: +m[3], to: +m[4], chance: +m[2] - +m[1] - 1, file });
}
if (!entries.length) die('no entries found');

// Renewal item_db: Id -> { type, slots, locations }
const items = new Map();
for (const file of git(RATHENA, 'ls-tree', '--name-only', PIN, 'db/re/').split('\n').filter(f => /\/item_db.*\.yml$/.test(f))) {
    let cur = null, inLoc = false;
    for (const line of show(file).split('\n')) {
        let m;
        if ((m = line.match(/^  - Id: (\d+)/))) { cur = { type: '', slots: 0, loc: [] }; items.set(+m[1], cur); inLoc = false; continue; }
        if (!cur) continue;
        if ((m = line.match(/^    Type: (\w+)/))) cur.type = m[1];
        else if ((m = line.match(/^    Slots: (\d+)/))) cur.slots = +m[1];
        else if (/^    Locations:/.test(line)) inLoc = true;
        else if (inLoc && (m = line.match(/^      (\w+): true/))) cur.loc.push(m[1]);
        else if (/^    \S/.test(line)) inLoc = false;
    }
}

const seen = new Set();
for (const e of entries) {
    const a = items.get(e.from), b = items.get(e.to);
    if (!a || !b) die(`${e.from} -> ${e.to} (${e.file}): not in the Renewal item_db`);
    if (!/^(Weapon|Armor)$/.test(a.type) || a.type !== b.type) die(`${e.from} -> ${e.to}: types ${a.type}/${b.type}`);
    if (a.loc.sort().join() !== b.loc.sort().join()) die(`${e.from} -> ${e.to}: places differ`);
    if (b.slots <= a.slots) die(`${e.from} -> ${e.to}: slots ${a.slots} -> ${b.slots}`);
    if (seen.has(e.from)) die(`${e.from} listed twice`);
    seen.add(e.from);
    if (e.chance < 1 || e.chance > 100) die(`${e.from}: chance ${e.chance}`);
}

// setarray lines of 12 entries each, indented like the NPC (4 spaces)
const IND = '    ';
const lines = [`${IND}// Generated by tools/slot-table.cjs from rAthena ${PIN.slice(0, 10)}`,
    `${IND}// (Seiyablem/Leablem: npc/merchants/socket_enchant.txt, socket_enchant2.txt).`,
    `${IND}// .slot_from: the item, .slot_to: its slotted twin, .slot_chance: success in %.`];
for (let i = 0; i < entries.length; i += 12) {
    const part = entries.slice(i, i + 12);
    lines.push(`${IND}setarray .slot_from[${i}], ${part.map(e => e.from).join(', ')};`);
    lines.push(`${IND}setarray .slot_to[${i}], ${part.map(e => e.to).join(', ')};`);
    lines.push(`${IND}setarray .slot_chance[${i}], ${part.map(e => e.chance).join(', ')};`);
}

const npcFile = path.join(ROOT, 'npc', 'enchanter.txt');
const src = fs.readFileSync(npcFile, 'utf8').replace(/\r\n/g, '\n');
const begin = `${IND}// --- slot table: begin ---\n`, end = `${IND}// --- slot table: end ---\n`;
const i = src.indexOf(begin), j = src.indexOf(end);
if (i < 0 || j < i) die(`markers not found in ${npcFile}`);
fs.writeFileSync(npcFile, src.slice(0, i + begin.length) + lines.join('\n') + '\n' + src.slice(j));
const byChance = {};
for (const e of entries) byChance[e.chance] = (byChance[e.chance] || 0) + 1;
console.log(`${entries.length} items written (rAthena ${PIN.slice(0, 10)}); by chance %: ${JSON.stringify(byChance)}`);
